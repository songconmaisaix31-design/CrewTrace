export const ERROR_CODES = {
  POLICY_UNREADABLE: 'SDK_POLICY_UNREADABLE',
  POLICY_INVALID: 'SDK_POLICY_INVALID',
  TRUST_ROOT_MISREPRESENTED: 'TRUST_ROOT_MISREPRESENTED',
  ALLOWLIST_MISSING_METADATA: 'ALLOWLIST_MISSING_METADATA',
  ALLOWLIST_FUTURE_DATED: 'ALLOWLIST_FUTURE_DATED',
  ALLOWLIST_STALE: 'ALLOWLIST_STALE',
  REVOCATION_LIST_MISSING_METADATA: 'REVOCATION_LIST_MISSING_METADATA',
  REVOCATION_LIST_FUTURE_DATED: 'REVOCATION_LIST_FUTURE_DATED',
  REVOCATION_LIST_STALE: 'REVOCATION_LIST_STALE',
  REVOCATION_LIST_REQUIRED: 'REVOCATION_LIST_REQUIRED',
  RULE_VERSION_EMPTY: 'RULE_VERSION_EMPTY',
} as const;

export type SdkErrorCode = typeof ERROR_CODES[keyof typeof ERROR_CODES];

export class TrustSdkError extends Error {
  readonly code: SdkErrorCode;

  constructor(code: SdkErrorCode, message: string) {
    super(`${code}: ${message}`);
    this.name = 'TrustSdkError';
    this.code = code;
  }
}
