import {chromium} from 'playwright';
import {writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
const out=fileURLToPath(new URL('./',import.meta.url));
const browser=await chromium.launch({channel:'chrome',headless:true,args:['--enable-unsafe-swiftshader']});
const context=await browser.newContext({viewport:{width:1440,height:900}});
const page=await context.newPage();
const evidence={};
await page.goto('http://127.0.0.1:5173/');
await page.getByRole('link',{name:'向下探索',exact:true}).waitFor();
await page.keyboard.press('Tab');
evidence.firstFocus=await page.evaluate(()=>document.activeElement.outerHTML);
await page.keyboard.press('Enter');await page.waitForTimeout(400);
evidence.skipFocus=await page.evaluate(()=>({class:document.activeElement.className,tag:document.activeElement.tagName}));
await page.keyboard.press('Tab');
evidence.afterSkipTab=await page.evaluate(()=>document.activeElement.outerHTML);
evidence.tabContrast=await page.locator('.stage-switch button').evaluateAll(els=>els.map(el=>({text:el.innerText,color:getComputedStyle(el).color,opacity:getComputedStyle(el).opacity,background:getComputedStyle(document.body).backgroundColor})));
await page.getByRole('link',{name:'CrewTrace 公开协作',exact:true}).click();
await page.getByRole('button',{name:'起名加入',exact:true}).click();
await page.locator('input[name="name"]').fill('审查本地未提交草稿');
await page.keyboard.press('Escape');await page.waitForTimeout(200);
await page.getByRole('button',{name:'起名加入',exact:true}).click();
evidence.draftAfterEscape=await page.locator('input[name="name"]').inputValue();
await page.keyboard.press('Escape');await page.waitForTimeout(200);
await page.getByRole('link',{name:'向下探索',exact:true}).click();
await page.getByRole('button',{name:'02 交流与公告',exact:true}).click();
evidence.panelBeforeReload=await page.locator('.collaboration-stage').getAttribute('data-panel');
await page.reload();await page.getByRole('button',{name:'01 协作任务',exact:true}).waitFor();
evidence.panelAfterReload=await page.locator('.collaboration-stage').getAttribute('data-panel');
await page.waitForTimeout(1500);
await page.locator('.public-record h3 button').first().click();
await page.waitForTimeout(1200);
await page.keyboard.press('Escape');await page.waitForTimeout(200);
await page.goBack();await page.waitForTimeout(700);
evidence.backAfterClose={url:page.url(),dialogCount:await page.locator('dialog[open]').count()};
await page.keyboard.press('Escape');await page.waitForTimeout(200);
await page.setViewportSize({width:320,height:450});
await page.waitForTimeout(400);
await page.screenshot({path:out+'workspace-320x450.png'});
evidence.compact=await page.evaluate(()=>({overflow:document.documentElement.scrollWidth>innerWidth,reading:document.querySelector('.stage-card-scroll').clientHeight}));
await page.getByRole('link',{name:'CrewTrace 公开协作',exact:true}).click();
await page.waitForTimeout(400);
await page.screenshot({path:out+'home-320x450.png'});
await page.getByRole('button',{name:'起名加入',exact:true}).click();
await page.waitForTimeout(400);
await page.screenshot({path:out+'join-320x450.png'});
evidence.compactInput=await page.locator('input[name="name"]').evaluate(el=>({font:getComputedStyle(el).fontSize,rect:el.getBoundingClientRect().toJSON()}));
await writeFile(out+'checks.json',JSON.stringify(evidence,null,2));
await browser.close();
