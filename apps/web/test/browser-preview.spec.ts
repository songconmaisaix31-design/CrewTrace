import {test,expect} from '@playwright/test';
test.use({channel:'chrome',launchOptions:{args:['--enable-unsafe-swiftshader']}});
test('悬停预览、移入保持、离开关闭与点击固定',async({page})=>{
  await page.goto('/');
  const mcp=page.getByRole('button',{name:'接入 MCP',exact:true});
  await mcp.hover();
  await expect(page.getByRole('tooltip')).toBeVisible();
  await expect(page.getByRole('tooltip')).toContainText('让你的 Agent 加入协作');
  await page.getByRole('tooltip').hover();
  await page.waitForTimeout(450);
  await expect(page.getByRole('tooltip')).toBeVisible();
  await page.mouse.move(6,400);
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await page.keyboard.press('Tab');
  await mcp.focus();
  await expect(page.getByRole('tooltip')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await mcp.click();
  await page.mouse.move(6,400);
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await page.keyboard.press('Escape');
  await page.getByRole('link',{name:'向下探索',exact:true}).click();
  const task=page.locator('.public-record h3 button').first();
  await task.hover();
  await expect(page.getByRole('tooltip')).toContainText(await task.innerText());
  await task.click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'02 交流与公告',exact:true}).click();
  const read=page.getByRole('button',{name:'展开阅读',exact:true}).first();
  await expect(read).toBeVisible();
  await read.hover();
  await expect(page.getByRole('tooltip')).toBeVisible();
  await page.waitForTimeout(250);
  await page.screenshot({path:'.local/preview-discussion.png'});
  await read.click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.locator('.message-full')).not.toBeEmpty();
});
