import { test, expect } from '@playwright/test';
test.use({channel:'chrome',launchOptions:{args:['--enable-unsafe-swiftshader']}});
test('淡入切页、惯性保护、同位面板往返与手机布局',async({page})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  const bounds=await page.locator('.experience-shell').boundingBox();
  expect(bounds).toEqual({x:0,y:0,width:1280,height:720});
  await expect(page.locator('.lens-scene .signal-scene')).toHaveCSS('mask-image',/radial-gradient/);
  await expect(page.locator('.experience-shell')).toHaveAttribute('data-screen','0');
  await page.mouse.move(6,350);
  await page.mouse.wheel(0,16);
  await expect(page.locator('.experience-shell')).toHaveAttribute('data-screen','1');
  await expect(page.locator('.stage-tasks')).toHaveCSS('animation-name','stage-surface-in');
  for(let i=0;i<5;i++)await page.mouse.wheel(0,120);
  // 触控板的间断惯性及后续增幅不应跨过 01。
  for(const delta of [80,45,24,60,18,10]){
    await page.waitForTimeout(110);
    await page.mouse.wheel(0,delta);
    await expect(page.locator('.stage-tasks')).toHaveAttribute('aria-hidden','false');
  }
  await expect(page.locator('.stage-tasks')).toHaveAttribute('aria-hidden','false');
  await page.waitForTimeout(1100);
  const first=await page.locator('.stage-tasks').boundingBox();
  const windowBox=await page.locator('.stage-window').boundingBox();
  const preview=await page.locator('.stage-discussion').boundingBox();
  expect(preview!.y).toBeLessThan(windowBox!.y+windowBox!.height);
  await expect(page.locator('.stage-discussion')).toHaveAttribute('inert','');
  await page.screenshot({path:'.local/stage-tasks.png'});
  const reading=page.locator('.stage-tasks .stage-card-scroll');
  await expect(page.getByRole('button',{name:'阅读内容',exact:true})).toHaveCount(0);
  const scrollable=await reading.evaluate(el=>el.scrollHeight>el.clientHeight);
  if(scrollable){
    await reading.evaluate(el=>{el.scrollTop=0;});
    await reading.hover();
    await page.mouse.wheel(0,40);
    await expect.poll(()=>reading.evaluate(el=>el.scrollTop)).toBeGreaterThan(0);
    await expect(page.locator('.stage-tasks')).toHaveAttribute('aria-hidden','false');
  }
  await page.waitForTimeout(350);
  await page.mouse.move(6,350);
  await page.mouse.wheel(0,16);
  await expect(page.locator('.stage-discussion')).toHaveAttribute('aria-hidden','false');
  await page.waitForTimeout(1100);
  const second=await page.locator('.stage-discussion').boundingBox();
  expect(Math.abs(first!.y-second!.y)).toBeLessThan(3);
  expect(second!.height).toBeLessThan(page.viewportSize()!.height*.65);
  await page.screenshot({path:'.local/stage-discussion.png'});
  await page.mouse.wheel(0,-200);
  await expect(page.locator('.stage-tasks')).toHaveAttribute('aria-hidden','false');
  await page.waitForTimeout(1000);
  await page.mouse.wheel(0,-300);
  await expect(page.locator('.experience-shell')).toHaveAttribute('data-screen','0');
  expect(await page.evaluate(()=>scrollY)).toBe(0);
  expect(await page.locator('.stage-card-scroll').first().evaluate(el=>getComputedStyle(el).overflowY)).toBe('auto');
  await page.getByRole('link',{name:'向下探索',exact:true}).click();
  await page.waitForTimeout(700);
  await page.mouse.move(6,350);
  await page.mouse.wheel(0,-45);
  await expect(page.locator('.experience-shell')).toHaveAttribute('data-screen','0');
  await page.getByRole('link',{name:'向下探索',exact:true}).click();
  await expect(page.locator('.stage-tasks')).toHaveAttribute('aria-hidden','false');
  await page.getByRole('button',{name:'下一屏：交流与公告',exact:true}).click();
  await expect(page.locator('.stage-discussion')).toHaveAttribute('aria-hidden','false');
  await page.getByRole('button',{name:'上一屏：协作任务',exact:true}).click();
  await expect(page.locator('.stage-tasks')).toHaveAttribute('aria-hidden','false');
  await page.getByRole('button',{name:'上一屏：首页',exact:true}).click();
  await expect(page.locator('.experience-shell')).toHaveAttribute('data-screen','0');
  await page.waitForTimeout(1100);
  await page.screenshot({path:'.local/lens-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(1100);
  await expect(page.locator('.public-topbar')).toHaveCount(1);
  await page.screenshot({path:'.local/lens-mobile.png'});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.getByRole('link',{name:'向下探索',exact:true}).click();
  await page.getByRole('button',{name:'02 交流与公告',exact:true}).click();
  await expect(page.locator('.stage-tasks')).toBeHidden();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'.local/stage-mobile.png'});
  expect(errors).toEqual([]);
});
