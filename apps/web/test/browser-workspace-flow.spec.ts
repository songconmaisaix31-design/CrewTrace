import {test,expect} from '@playwright/test';
test.use({channel:'chrome',launchOptions:{args:['--enable-unsafe-swiftshader']}});

for(const width of [1440,390])test(`任务发布、身份入口、完整筛选和任务交流保持范围清楚 ${width}`,async({page})=>{
  await page.setViewportSize({width,height:844});
  await page.goto('/');
  await page.getByRole('link',{name:'向下探索',exact:true}).click();
  const tasks=page.locator('.stage-tasks');
  await expect(tasks.getByRole('button',{name:'发布任务',exact:true})).toBeVisible();
  await page.waitForTimeout(350);
  const browseBox=(await tasks.getByRole('button',{name:'浏览全部任务',exact:true}).boundingBox())!;
  const postBox=(await tasks.getByRole('button',{name:'发布任务',exact:true}).boundingBox())!;
  expect(Math.abs(browseBox.y-postBox.y)).toBeLessThan(2);
  expect(browseBox.x+browseBox.width).toBeLessThanOrEqual(postBox.x);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:`.local/task-entry-${width}.png`});
  await tasks.getByRole('button',{name:'发布任务',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'你的 Agent 身份',exact:true})).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button',{name:'管理协作身份',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'你的 Agent 身份',exact:true})).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await tasks.locator('.public-record').first().waitFor();
  await tasks.locator('select').selectOption('COMPLETED');
  await tasks.getByRole('button',{name:'浏览全部任务',exact:true}).click();
  const all=page.getByRole('dialog',{name:'全部任务',exact:true});
  await expect(all.locator('select')).toHaveValue('COMPLETED');
  const response=page.waitForResponse(r=>r.url().includes('tasks')&&r.url().includes('offset')&&!r.url().includes('COMPLETED')&&r.status()===200);
  await all.locator('select').selectOption('');
  await response;
  await all.locator('.public-record h3 button').first().click();
  const detail=page.getByRole('dialog',{name:'协作详情',exact:true});
  await expect(detail.locator('.public-task-detail')).toBeVisible();
  const id=await detail.locator('.public-task-detail').getAttribute('data-task-id');
  const discussion=page.waitForRequest(r=>r.url().includes('messages')&&decodeURIComponent(r.url()).includes(`taskId=${id}`));
  await detail.getByRole('button',{name:'任务交流',exact:true}).click();
  await discussion;
  await expect(detail.getByText('这里的消息会关联到当前任务。')).toBeVisible();
  await page.screenshot({path:`.local/task-discussion-${width}.png`});
  await detail.getByRole('button',{name:'发布消息',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'你的 Agent 身份',exact:true})).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog',{name:'你的 Agent 身份',exact:true})).toHaveCount(0);
  await expect(detail).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(detail).toHaveCount(0);
  await page.getByRole('button',{name:'02 交流',exact:true}).click();
  await expect(page.locator('.stage-discussion .public-message').first()).toBeVisible();
  const refreshed=page.waitForRequest(r=>r.url().includes('messages')&&decodeURIComponent(r.url()).includes('after=0')&&!r.url().includes('taskId'));
  await page.getByRole('button',{name:'刷新公开协作',exact:true}).click();
  await refreshed;
  await expect(page.locator('.stage-discussion .public-message').first()).toBeVisible();
});
