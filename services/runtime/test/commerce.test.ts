test('配置和金额边界拒绝缺少密钥、错环境、超额与无效凭证',()=>{
  assert.equal(ConfigSchema.parse({}).PAYMENT_MODE,'disabled');
  assert.throws(()=>ConfigSchema.parse({PAYMENT_MODE:'production'}));
  assert.throws(()=>ConfigSchema.parse({PAYMENT_MODE:'sandbox',ALIPAY_GATEWAY:'https://example.com'}));
  assert.equal(amountFen('0.01'),1);assert.equal(amountFen('50.00'),5000);
  for(const value of ['0.001','-1','1e2',1,null])assert.throws(()=>amountFen(value));
  assert.throws(()=>decodeProof('not valid base64!'));
  assert.throws(()=>decodeProof(Buffer.from('{}').toString('base64')));
  assert.throws(()=>ServiceSchema.parse({title:'越界价格',description:'服务参数验证必须拒绝超过官方金额上限的报价',category:'其他',priceFen:5001,deliveryHours:1}));
});

test('真实 PostgreSQL、HTTP 与官方 MCP：订单、双身份履约、权限、并发、持久化',async t=>{
  const directory=await mkdtemp(resolve('../../.local/commerce-'));
  const config=ConfigSchema.parse({DATABASE_URL:`pglite://${directory}`,PUBLIC_BASE_URL:'http://127.0.0.1:3000',ADMIN_TOKEN:randomUUID()});
  let db=new Database(config.DATABASE_URL);await db.migrate();await db.migrate();
  const app=new Commerce(db,config),http=createHttp(app);
  const server=serve({fetch:http.fetch,hostname:'127.0.0.1',port:0});
  await new Promise<void>(res=>server.on('listening',res));
  const address=server.address();assert.ok(address&&typeof address==='object');
  const base=`http://127.0.0.1:${address.port}`;
  const call=async(path:string,token='',body?:unknown,method?:string)=>{
    const response=await fetch(base+path,{method:method??(body===undefined?'GET':'POST'),headers:{...(token?{Authorization:`Bearer ${token}`} :{}),...(body===undefined?{}:{'Content-Type':'application/json'})},body:body===undefined?undefined:JSON.stringify(body)});
    return {status:response.status,body:await response.json() as any};
  };
  t.after(async()=>{await new Promise<void>((res,rej)=>server.close(e=>e?rej(e):res()));await db.close();await rm(directory,{recursive:true,force:true});});
  const buyer=await call('/api/identities','',{name:'验收买家',bio:'运行真实服务验收'});
  const seller=await call('/api/identities','',{name:'验收提供者',bio:'实际审阅当前项目依赖清单'});
  const stranger=await call('/api/identities','',{name:'独立身份'});
  assert.equal(buyer.status,201);const bt=buyer.body.credential,st=seller.body.credential;
  const manifest=JSON.parse(await readFile(new URL('../package.json',import.meta.url),'utf8'));
  const records=Object.entries(manifest.dependencies).map(([name,version])=>`${name},${version}`);
  const csv=`package,version\n${records.join('\n')}`;
  const listing=await call('/api/services');assert.equal(listing.body.services[0].id,'csv-quality');
  const request={serviceId:'csv-quality',input:csv,idempotencyKey:randomUUID(),expectedVersion:1,maxAmountFen:0};
  const created=await Promise.all([call('/api/orders',bt,request),call('/api/orders',bt,request)]);
  assert.equal(created[0].status,201);assert.equal(created[0].body.id,created[1].body.id);
  const oid=created[0].body.id;
  assert.equal((await call('/api/orders',bt,{...request,input:csv+'\n'})).status,409);
  assert.equal((await call(`/api/orders/${oid}`,stranger.body.credential)).status,403);
  assert.equal((await call(`/api/orders/${oid}`)).status,401);
  assert.equal((await call(`/api/orders/${oid}/deliveries`,bt,{content:'买家不应提交自己购买的服务交付记录。'})).status,403);
  const results=await Promise.all([call(`/api/orders/${oid}/execute`,bt,{}),call(`/api/orders/${oid}/execute`,bt,{})]);
  assert.ok(results.every(r=>r.status===200));
  const detail=await call(`/api/orders/${oid}`,bt);assert.equal(detail.body.deliveries.length,1);assert.match(detail.body.deliveries[0].content,new RegExp(`数据行数：${records.length}`));
  assert.equal(detail.body.order.payment_status,'FREE');
  const accepted={decision:'accept',deliveryVersion:1,rating:5,comment:'已核对源 package.json 的依赖行数，报告与实际文件一致。'};
  assert.equal((await call(`/api/orders/${oid}/review`,bt,{...accepted,deliveryVersion:2})).status,409);
  await Promise.all([call(`/api/orders/${oid}/review`,bt,accepted),call(`/api/orders/${oid}/review`,bt,accepted)]);
  const rep=await call('/api/services/csv-quality/reputation');assert.equal(rep.body.reviews.length,1);assert.equal(rep.body.reviews[0].paid,false);
  const svc=await call('/api/services',st,{title:'项目依赖清单审阅',description:'阅读实际 package.json，提交依赖分类与版本数量核对报告，买家依据源文件验收。',category:'代码审查',priceFen:0,deliveryHours:2});
  assert.equal(svc.status,201);
  const external=await call('/api/orders',bt,{...request,idempotencyKey:randomUUID(),serviceId:svc.body.id,input:'请审阅 CrewTrace runtime package.json，检查依赖数量并返回 Markdown。'});
  const eid=external.body.id;
  assert.equal((await call(`/api/orders/${eid}/execute`,bt,{})).status,403);
  assert.equal((await call(`/api/orders/${eid}/execute`,st,{})).status,200);
  const first=inspectCSV(csv);
  assert.equal((await call(`/api/orders/${eid}/deliveries`,st,{content:first})).status,201);
  assert.equal((await call(`/api/orders/${eid}/review`,st,accepted)).status,403);
  await call(`/api/orders/${eid}/review`,bt,{decision:'revise',deliveryVersion:1,comment:'请补充 package.json 原始字节数，便于核对数据来源。'});
  const bytes=(await stat(new URL('../package.json',import.meta.url))).size;
  const final=first+`\n\n源文件：services/runtime/package.json；实际大小：${bytes} 字节。`;
  const delivery=await call(`/api/orders/${eid}/deliveries`,st,{content:final});assert.equal(delivery.body.version,2);
  assert.equal((await call(`/api/orders/${eid}/review`,bt,accepted)).status,409);
  assert.equal((await call(`/api/orders/${eid}/review`,bt,{...accepted,deliveryVersion:2})).status,200);
  const events=(await call(`/api/orders/${eid}`,bt)).body.events;assert.deepEqual(events.map((e:any)=>e.kind),['ORDER_CREATED','WORK_STARTED','DELIVERY_SUBMITTED','REVISION_REQUESTED','DELIVERY_SUBMITTED','ACCEPTED']);
  const paid=await call('/api/services',st,{title:'付费依赖审阅服务',description:'完整审阅项目依赖及许可证，提供实际检查记录和风险定位建议。',category:'代码审查',priceFen:100,deliveryHours:24});assert.equal(paid.body.published,false);
  assert.equal((await call('/api/services')).body.services.some((s:any)=>s.id===paid.body.id),false);
  assert.equal((await call(`/api/admin/services/${paid.body.id}/binding`,config.ADMIN_TOKEN,{serviceId:'unregistered',resourceId:'unregistered'})).status,503);
  assert.equal((await call('/api/admin/metrics',bt)).status,403);
  const metrics=await call('/api/admin/metrics',config.ADMIN_TOKEN);assert.equal(metrics.body.verified_payments,0);assert.equal(metrics.body.revenue_fen,0);
  assert.equal((await call(`/api/orders/${eid}/dispute`,bt,{reason:'申请商户复核已交付依赖清单的文件来源。'})).status,200);
  const disputes=await call('/api/admin/disputes',config.ADMIN_TOKEN);assert.equal(disputes.body.orders[0].latest_delivery,final);
  assert.equal((await call(`/api/admin/orders/${eid}/resolve`,st,{reason:'提供者不能代替商户处理售后。'})).status,403);
  assert.equal((await call(`/api/admin/orders/${eid}/resolve`,config.ADMIN_TOKEN,{reason:'已对照真实源文件复核，双方确认恢复验收记录。'})).body.status,'ACCEPTED');
  assert.equal((await call(`/api/admin/orders/${eid}/refund`,config.ADMIN_TOKEN,{})).status,409);
  assert.equal((await call(`/api/admin/services/${svc.body.id}/price`,config.ADMIN_TOKEN,{priceFen:100},'PATCH')).body.published,false);
  assert.equal((await call(`/api/orders/${eid}`,bt)).body.order.price_fen,0);
  assert.equal((await fetch(`${base}/api/identities`,{method:'POST',headers:{Origin:'https://attacker.invalid','Content-Type':'application/json'},body:JSON.stringify({name:'外部来源'})})).status,403);
  const client=new Client({name:'crewtrace-acceptance',version:'1.0.0'});
  await client.connect(new StreamableHTTPClientTransport(new URL(base+'/mcp')));
  const tools=await client.listTools();assert.ok(tools.tools.some(tool=>tool.name==='verify_payment'));
  const mcpOrder=await client.callTool({name:'get_order',arguments:{orderId:eid,credential:bt}});
  assert.equal(mcpOrder.isError,undefined);assert.ok(JSON.stringify(mcpOrder).includes('ACCEPTED'));
  const denied=await client.callTool({name:'get_order',arguments:{orderId:eid,credential:stranger.body.credential}});assert.equal(denied.isError,true);
  await client.close();
  const rotated=await call('/api/me/rotate',bt,{});assert.equal((await call('/api/me',bt)).status,401);assert.equal((await call('/api/me',rotated.body.credential)).status,200);
  const rows=await db.query('SELECT kind FROM ct_events WHERE order_id=$1 ORDER BY seq',[eid]);assert.equal(rows.rows.length,8);
  await db.close();db=new Database(config.DATABASE_URL);
  const persisted=await new Commerce(db,config).detail(buyer.body.actor,eid);assert.equal(persisted.deliveries.length,2);assert.equal(persisted.order.status,'ACCEPTED');
});
